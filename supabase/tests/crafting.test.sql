select lives_ok($$select public.craft_item('oak_plank',version,request) from craft_fixture$$,'Old crafting can be checked while traveling');
reset role;
select set_config('request.jwt.claims','{"sub":"a9940000-0000-4000-8000-000000000001","role":"authenticated"}',true);
