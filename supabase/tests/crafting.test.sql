update private.character_skills set xp=9007199254740986 where character_id=(select a from craft_fixture) and skill_id='crafting';
set local role authenticated;
select throws_ok($$select public.craft_item('oak_plank',version,gen_random_uuid()) from craft_fixture$$,'P0001','SKILL_XP_LIMIT','Crafting rejects a partial XP award at the storage limit');
reset role;
select is((select quantity from private.item_stacks where character_id=(select a from craft_fixture) and item_id='oak_logs'),5::bigint,'XP limit preserves ingredients');
