select throws_ok('update private.crafting_ingredients set quantity=1','42501',null,'Players cannot choose material costs');
select throws_ok($$select public.craft_item('oak_plank',null,gen_random_uuid())$$,'22023','INVALID_REQUEST','Missing offer is rejected');
select throws_ok($$select public.craft_item('oak_plank',repeat('a',64),null)$$,'22023','INVALID_REQUEST','Missing receipt ID is rejected');
select throws_ok($$select public.craft_item('missing',version,gen_random_uuid()) from craft_fixture$$,'22023','INVALID_RECIPE','Unknown recipe is rejected');
select throws_ok($$select public.craft_item('oak_plank',repeat('a',64),gen_random_uuid())$$,'P0001','STALE_OFFER','Old or forged costs are rejected');
insert into craft_results select 'first',public.craft_item('oak_plank',version,request) from craft_fixture;
select is((select value#>>'{output,item_id}' from craft_results where key='first'),'oak_planks','Crafting uses the existing plank definition');
select is((select value#>>'{progression,xp_awarded}' from craft_results where key='first'),'10','Receipt records Crafting XP');
select is(public.list_crafting_recipes()#>>'{0,ingredients,0,owned}','7','Exactly five logs are consumed');
select is(public.list_crafting_recipes()#>>'{0,output,owned}','1','Plank arrives instantly in inventory');
select is((select public.craft_item('oak_plank',version,request) from craft_fixture),(select value from craft_results where key='first'),'Replay returns the identical saved receipt');
select throws_ok($$select public.craft_item('oak_plank',repeat('b',64),request) from craft_fixture$$,'22023','REQUEST_CONFLICT','A saved request cannot change its offer');
select throws_ok($$select public.craft_item('other',version,request) from craft_fixture$$,'22023','REQUEST_CONFLICT','A saved request cannot change recipe');
reset role;
select is((select quantity from private.item_stacks where character_id=(select a from craft_fixture) and item_id='oak_logs'),7::bigint,'Replay never consumes a second set of logs');
select is((select energy from public.characters where id=(select a from craft_fixture)),0,'Crafting needs no Energy');
select is((select stamina from public.characters where id=(select a from craft_fixture)),0,'Crafting needs no Stamina');
select is((select gold_coins from public.characters where id=(select a from craft_fixture)),(select gold from craft_before),'Crafting charges no gold');
select is((select xp from private.character_skills where character_id=(select a from craft_fixture) and skill_id='crafting'),10::bigint,'Crafting awards ten XP exactly once including receipt replay');
select is((select total from private.item_circulation where item_id='oak_logs'),(select logs-5 from craft_before),'Circulation tracks consumed logs');
select is((select total from private.item_circulation where item_id='oak_planks'),(select planks+1 from craft_before),'Circulation tracks new planks');
select ok(exists(select 1 from private.character_actions where character_id=(select a from craft_fixture)),'Crafting records Last action');
create temporary table craft_action_before as select last_action_at from private.character_actions where character_id=(select a from craft_fixture);
select public.craft_item('oak_plank',version,request) from craft_fixture;
select is((select last_action_at from private.character_actions where character_id=(select a from craft_fixture)),(select last_action_at from craft_action_before),'Receipt checks do not advance Last action');
select ok(exists(select 1 from public.player_game_events where character_id=(select a from craft_fixture)),'Crafting publishes a game refresh event');
update private.crafting_recipes set active=false where id='oak_plank';
set local role authenticated;
select is(jsonb_array_length(public.list_crafting_recipes()),0,'Disabled recipes are hidden');
select is((select public.craft_item('oak_plank',version,request) from craft_fixture),(select value from craft_results where key='first'),'Receipt survives disabled recipe');
select throws_ok($$select public.craft_item('oak_plank',version,gen_random_uuid()) from craft_fixture$$,'22023','INVALID_RECIPE','Disabled recipe rejects new crafting');
reset role;
update private.crafting_recipes set active=true where id='oak_plank';
update private.item_definitions set active=false where id='oak_logs';
set local role authenticated;
select is(jsonb_array_length(public.list_crafting_recipes()),0,'Unavailable material hides recipe');
select throws_ok($$select public.craft_item('oak_plank',version,gen_random_uuid()) from craft_fixture$$,'P0001','RECIPE_UNAVAILABLE','Disabled materials reject crafting');
reset role;
update private.item_definitions set active=true where id='oak_logs';
update private.item_stacks set quantity=9007199254740991 where character_id=(select a from craft_fixture) and item_id='oak_planks';
set local role authenticated;
select throws_ok($$select public.craft_item('oak_plank',version,gen_random_uuid()) from craft_fixture$$,'P0001','INVENTORY_FULL','Full output stack rejects crafting');
reset role;
select is((select quantity from private.item_stacks where character_id=(select a from craft_fixture) and item_id='oak_logs'),7::bigint,'Full output stack does not consume ingredients');
update private.item_stacks set quantity=1 where character_id=(select a from craft_fixture) and item_id='oak_planks';
savepoint craft_atomic;
select public.craft_item('oak_plank',version,gen_random_uuid()) from craft_fixture;
rollback to savepoint craft_atomic;
select is((select quantity from private.item_stacks where character_id=(select a from craft_fixture) and item_id='oak_logs'),7::bigint,'Rollback restores ingredients');
select is((select quantity from private.item_stacks where character_id=(select a from craft_fixture) and item_id='oak_planks'),1::bigint,'Rollback removes output');
select is((select count(*) from private.crafting_requests where character_id=(select a from craft_fixture)),1::bigint,'Rollback removes receipt');
select is((select xp from private.character_skills where character_id=(select a from craft_fixture) and skill_id='crafting'),10::bigint,'Transaction rollback restores XP');
set local role authenticated;
select public.craft_item('oak_plank',version,gen_random_uuid()) from craft_fixture;
select throws_ok($$select public.craft_item('oak_plank',version,gen_random_uuid()) from craft_fixture$$,'P0001','INSUFFICIENT_MATERIALS','Too few logs rejects crafting');
select is(public.list_crafting_recipes()#>>'{0,ingredients,0,owned}','2','Insufficient materials never change stock');
select is(public.list_crafting_recipes()#>>'{0,output,owned}','2','Outputs stack together');
reset role;
select is((select quantity from private.item_stacks where character_id=(select b from craft_fixture) and item_id='oak_logs'),5::bigint,'Another captain inventory is untouched');
select is((select xp from private.character_skills where character_id=(select a from craft_fixture) and skill_id='crafting'),20::bigint,'Rejected crafting never awards XP');
