select throws_ok($$select public.craft_item('oak_plank',repeat('a',64),gen_random_uuid())$$,'42501',null,'Anonymous Auth users cannot craft');
reset role;
select set_config('request.jwt.claims','{"sub":"a9940000-0000-4000-8000-000000000001","role":"authenticated"}',true);
set local role authenticated;
select is(public.list_crafting_recipes()#>>'{0,ingredients,0,owned}','12','Recipes show only the owner inventory');
select is(public.list_crafting_recipes()#>>'{0,ingredients,0,quantity}','5','Oak plank requires five logs');
select is(public.list_crafting_recipes()#>>'{0,output,quantity}','1','Recipe yields one plank');
