('a9940000-0000-4000-8000-000000000001','craft-one@example.test',false,'{"character_name":"CraftCaptain"}'),
('a9940000-0000-4000-8000-000000000002','craft-two@example.test',false,'{"character_name":"CraftOther"}'),
('a9940000-0000-4000-8000-000000000003','craft-anon@example.test',true,'{}');
create temporary table craft_fixture as select
(select id from public.characters where user_id='a9940000-0000-4000-8000-000000000001') a,
(select id from public.characters where user_id='a9940000-0000-4000-8000-000000000002') b,
(select version from private.crafting_recipes where id='oak_plank') version,gen_random_uuid() request;
grant select on craft_fixture to authenticated;
