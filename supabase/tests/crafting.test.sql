set local role authenticated;
select public.craft_item('oak_plank',version,request) from craft_fixture;
select is(public.list_crafting_recipes()#>>'{0,ingredients,0,owned}','0','Exact-cost crafting leaves no logs');
select is((public.get_own_skills()->>'character_level')::integer,8,'Crafting level-up updates Character Level');
reset role;
select is((select count(*) from private.item_stacks where character_id=(select b from craft_fixture) and item_id='oak_logs'),0::bigint,'Empty stacks are deleted');
select is((select count(*) from private.crafting_requests where request_id=(select request from craft_fixture)),2::bigint,'Receipt UUID is isolated per character');
