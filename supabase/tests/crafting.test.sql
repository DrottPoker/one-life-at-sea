  stamina_updated_at=clock_timestamp()+interval '1 day',morale_updated_at=clock_timestamp()+interval '1 day'
  where id in(select a from craft_fixture union all select b from craft_fixture);
insert into private.item_stacks(character_id,item_id,quantity) select a,'oak_logs',12 from craft_fixture;
insert into private.item_stacks(character_id,item_id,quantity) select b,'oak_logs',5 from craft_fixture;
create temporary table craft_before as select
(select total from private.item_circulation where item_id='oak_logs') logs,
(select total from private.item_circulation where item_id='oak_planks') planks,
(select gold_coins from public.characters where id=(select a from craft_fixture)) gold;
set local role anon;
select throws_ok('select public.list_crafting_recipes()','42501',null,'Logged-out users cannot read private crafting stock');
select throws_ok($$select public.craft_item('oak_plank',repeat('a',64),gen_random_uuid())$$,'42501',null,'Logged-out users cannot craft');
